// Builds docs/decisions/README.md from the records' frontmatter.
// `node scripts/decisions.mjs` writes the index. `--check` fails when a record is invalid or the index is stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '..', 'docs', 'decisions');
const indexPath = join(dir, 'README.md');
const keys = new Set([
  'status',
  'strength',
  'date',
  'revisit',
  'supersedes',
  'superseded_by',
]);
const errors = [];

const records = readdirSync(dir)
  .filter((file) => /^\d{4}-[a-z0-9-]+\.md$/.test(file))
  .sort()
  .map((file) => {
    const text = readFileSync(join(dir, file), 'utf8');
    const id = file.slice(0, 4);
    const [, head = '', body = ''] =
      text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/) ?? [];
    const meta = {};
    if (!head) errors.push(`${file}: missing frontmatter`);
    for (const line of head.split('\n').filter((l) => l.trim())) {
      const at = line.indexOf(':');
      const key = line.slice(0, at).trim();
      if (!keys.has(key))
        errors.push(`${file}: unknown frontmatter key "${key}"`);
      meta[key] = line.slice(at + 1).trim();
    }
    const title = body.match(/^# (\d{4})\. (.+)$/m);
    if (!title || title[1] !== id)
      errors.push(`${file}: heading must be "# ${id}. <title>"`);
    return { id, file, title: title?.[2] ?? '', ...meta };
  });

const byId = new Map(records.map((r) => [r.id, r]));
for (const r of records) {
  if (byId.get(r.id) !== r) errors.push(`${r.file}: duplicate id ${r.id}`);
  if (!['proposed', 'accepted', 'superseded'].includes(r.status))
    errors.push(`${r.file}: status must be proposed, accepted or superseded`);
  if (!['lock', 'default'].includes(r.strength))
    errors.push(`${r.file}: strength must be lock or default`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(r.date ?? ''))
    errors.push(`${r.file}: date must be YYYY-MM-DD`);
  if (!r.revisit) errors.push(`${r.file}: revisit is required`);
  if ((r.status === 'superseded') !== Boolean(r.superseded_by))
    errors.push(
      `${r.file}: superseded_by is set exactly when status is superseded`,
    );
  if (r.superseded_by && byId.get(r.superseded_by)?.supersedes !== r.id)
    errors.push(`${r.file}: ${r.superseded_by} must say "supersedes: ${r.id}"`);
  if (r.supersedes && !byId.has(r.supersedes))
    errors.push(`${r.file}: supersedes unknown record ${r.supersedes}`);
  const old = byId.get(r.supersedes);
  if (r.status === 'accepted' && old && old.superseded_by !== r.id)
    errors.push(
      `${old.file}: must be superseded with "superseded_by: ${r.id}"`,
    );
}

const cell = (s) => s.replaceAll('|', '\\|');
const table = (rows) =>
  rows.length === 0
    ? 'None.\n'
    : `| ID | Decision | Strength | Revisit when |\n| --- | --- | --- | --- |\n${rows
        .map(
          (r) =>
            `| [${r.id}](${r.file}) | ${cell(r.title)} | ${r.strength} | ${cell(r.revisit)} |`,
        )
        .join('\n')}\n`;
const superseded = records.filter((r) => r.status === 'superseded').length;
const index = `# Decisions

Generated by \`npm run decisions\` from each record's frontmatter. Do not edit by hand.

Read the decision rules in [AGENTS.md](../../AGENTS.md#decisions) before you rely on a record or change one. Open only the records that bear on your task.

## In force

${table(records.filter((r) => r.status === 'accepted'))}
## Proposed

These are not decided yet. Treat them as context, not rules.

${table(records.filter((r) => r.status === 'proposed'))}
${superseded} superseded ${superseded === 1 ? 'record is' : 'records are'} history and not listed. Do not follow them.
`;

if (errors.length > 0) {
  console.error(errors.join('\n'));
  process.exit(1);
}
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(indexPath, 'utf8');
  } catch {}
  if (current !== index) {
    console.error(
      'docs/decisions/README.md is stale. Run `npm run decisions`.',
    );
    process.exit(1);
  }
} else {
  writeFileSync(indexPath, index);
}
